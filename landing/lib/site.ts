import type { Metadata, MetadataRoute, ResolvingMetadata } from "next";

/**
 * Канонический адрес сайта — один источник для `metadataBase`, карты сайта и
 * robots.txt. Если развести их по файлам, абсолютные URL рано или поздно
 * разойдутся, и поисковик посчитает два написания одного адреса разными
 * страницами с одинаковым содержимым.
 *
 * Пока это домен деплоя на Vercel: своего домена у продукта ещё нет. Когда
 * он появится, менять здесь — и только здесь, но сделать это нужно до того,
 * как vercel.app-адреса осядут в индексе. Иначе смена строки превращается в
 * переезд: редиректы со старых URL, склейка сигналов, ожидание переобхода.
 *
 * Без протокола и с хвостовым слэшем `new URL(...)` в layout соберёт мусор,
 * поэтому строка ровно в таком виде.
 */
export const SITE_URL = "https://bazilik-web.vercel.app";

/** Имя бренда в `og:site_name` и в JSON-LD. */
export const SITE_NAME = "Базилик";

/** Латинское написание — в футере и в `alternateName` JSON-LD. */
export const SITE_NAME_LATIN = "Bazilik";

/**
 * Заголовок главной.
 *
 * Раньше в title стоял только слоган: «Базилик — готовь то, что уже есть».
 * Для продукта без запуска и узнаваемости это проигрышный ход — по запросу
 * «Базилик» ищут траву, а категорийного слова в заголовке не было вовсе.
 * Слоган сохранён (бренд-бук §Голос), но теперь после категории.
 *
 * «Меню на неделю», а не «план питания»: главная — это аудитория «дома»
 * (см. HOME в content.ts), а «план питания» в русском поиске тянет за собой
 * диетологический контекст, то есть намерение страницы /specialists.
 *
 * Живёт здесь, а не в layout.tsx, потому что тот же текст нужен карточке
 * ссылки как `alt` (app/opengraph-image.tsx). Пока это были две строки в
 * двух файлах, правка заголовка молча оставляла `og:image:alt` со старым.
 */
export const HOME_TITLE = "Базилик — меню на неделю: готовь то, что уже есть";

/**
 * Поля `openGraph`, одинаковые для всех страниц.
 *
 * Дочерний `openGraph` замещает родительский целиком, а не дополняет его,
 * поэтому каждая страница обязана перечислить их заново. Раскладывать
 * спредом из одного места, а не переписывать: так `og:site_name` и локаль
 * не разъедутся между страницами. Приём описан в
 * docs/01-app/03-api-reference/04-functions/generate-metadata.md, раздел
 * «Merging».
 */
export const OG_SHARED = {
  siteName: SITE_NAME,
  locale: "ru_RU",
  type: "website",
} as const satisfies Metadata["openGraph"];

/**
 * Картинка родительского сегмента, перенесённая в метаданные страницы.
 *
 * `opengraph-image.tsx` лежит в корне и раздаёт `og:image` всем маршрутам —
 * но только тем, кто не объявил свой `openGraph`. Как только страница его
 * объявляет (а ради собственного `og:url` это делает каждая), картинка
 * пропадает вместе с остальными унаследованными полями, а `twitter:card`
 * откатывается в `summary`. Отсюда явный перенос через `parent`.
 *
 * Пропажа не ломает сборку и не видна на странице — заметить её можно
 * только в отладчике ссылок, поэтому шаг вынесен в функцию с именем: его
 * забывают не по невнимательности, а потому что забыть нечего.
 */
export async function inheritedOgImages(
  parent: ResolvingMetadata,
  alt: string,
) {
  const images = (await parent).openGraph?.images ?? [];
  /**
   * Картинка общая, а `alt` — нет: у родителя он равен заголовку главной,
   * и без замены /specialists уносил в `og:image:alt` чужой title. Alt
   * страницы — её собственный заголовок, как и у корня.
   */
  return images.map((image) =>
    typeof image === "string" || image instanceof URL
      ? { url: image, alt }
      : { ...image, alt },
  );
}

/**
 * Тип берётся из самого Next, а не переписывается руками: свой союз из
 * пары значений пришлось бы править ради каждого нового маршрута и он
 * молча разъехался бы с тем, что Next на самом деле принимает.
 */
type ChangeFrequency = NonNullable<
  MetadataRoute.Sitemap[number]["changeFrequency"]
>;

export type SiteRoute = {
  path: string;
  changeFrequency: ChangeFrequency;
  priority: number;
};

/**
 * Маршруты, которые уходят в sitemap.xml.
 *
 * `/specialists` в списке нет: раздел не входит в MVP (см. `NAV_LINKS_HOME`
 * в content.ts и `hideRoutes` у `CtaSection` в app/page.tsx) и до запуска
 * не должен появляться в выдаче. Одного отсутствия здесь для этого мало —
 * карта сайта не запрещает индексацию, а лишь не помогает найти страницу.
 * Запрет ставит сама страница: `robots.index: false` в
 * app/specialists/page.tsx. Возвращать маршрут сюда одновременно со снятием
 * того флага, не отдельно от него.
 *
 * `/cookies` тоже нет, пока это заглушка «Страница в разработке»: она под
 * `robots.index: false` в app/cookies/page.tsx. Появится текст — снять
 * флаг и вернуть маршрут сюда одним коммитом, с `priority` около 0.1:
 * страница служебная и не должна конкурировать в выдаче с продуктовыми.
 *
 * `/home` в списке нет сознательно: он отдаёт 308 на `/` (см. next.config.ts),
 * а редиректы в карте сайта — ошибка обхода, а не подсказка.
 */
export const SITEMAP_ROUTES: readonly SiteRoute[] = [
  { path: "/", changeFrequency: "monthly", priority: 1 },
];

/**
 * Абсолютный URL маршрута — для sitemap и любых полей, где нужен полный адрес.
 *
 * Хвостовой слэш срезается сознательно: `new URL("/", ...)` даёт адрес со
 * слэшем на конце, а Next.js в `<link rel="canonical">` для корня пишет его
 * без слэша. Разойдись они, карта сайта и canonical
 * указывали бы на два формально разных адреса одной страницы, то есть ровно
 * на ту неоднозначность, ради устранения которой canonical и ставится.
 */
export function absoluteUrl(path: string): string {
  const href = new URL(path, SITE_URL).href;
  return href.endsWith("/") ? href.slice(0, -1) : href;
}
