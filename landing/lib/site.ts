/**
 * Канонический адрес сайта — один источник для `metadataBase`, карты сайта и
 * robots.txt. Если развести их по файлам, абсолютные URL рано или поздно
 * разойдутся, и поисковик посчитает два написания одного адреса разными
 * страницами с одинаковым содержимым.
 *
 * Пока это домен деплоя на Vercel: своего домена у продукта ещё нет. Когда
 * он появится, менять здесь — и только здесь, но сделать это нужно до того,
 * как vercel.app-адреса осядут в индексе. Иначе смена строки превращается в
 * переезд: редиректы со старых URL, склейка сигналов, ожидание переобхода.
 *
 * Без протокола и с хвостовым слэшем `new URL(...)` в layout соберёт мусор,
 * поэтому строка ровно в таком виде.
 */
export const SITE_URL = "https://bazilik-web.vercel.app";

export type SiteRoute = {
  path: string;
  changeFrequency: "monthly" | "yearly";
  priority: number;
};

/**
 * Маршруты, которые уходят в sitemap.xml.
 *
 * `/specialists` в списке нет: раздел не входит в MVP (см. `NAV_LINKS_HOME`
 * и `hideRoutes` в content.ts) и до запуска не должен появляться в выдаче.
 * Одного отсутствия здесь для этого мало — карта сайта не запрещает
 * индексацию, а лишь не помогает найти страницу. Запрет ставит сама
 * страница: `robots.index: false` в app/specialists/page.tsx. Возвращать
 * маршрут сюда одновременно со снятием того флага, не отдельно от него.
 *
 * `/cookies` — служебная страница: должна быть достижимой, но не должна
 * конкурировать в выдаче с продуктовыми, отсюда минимальный приоритет.
 *
 * `/home` в списке нет сознательно: он отдаёт 308 на `/` (см. next.config.ts),
 * а редиректы в карте сайта — ошибка обхода, а не подсказка.
 */
export const SITEMAP_ROUTES: readonly SiteRoute[] = [
  { path: "/", changeFrequency: "monthly", priority: 1 },
  { path: "/cookies", changeFrequency: "yearly", priority: 0.1 },
] as const;

/**
 * Абсолютный URL маршрута — для sitemap и любых полей, где нужен полный адрес.
 *
 * Хвостовой слэш срезается сознательно: `new URL("/", ...)` даёт адрес со
 * слэшем на конце, а Next.js в `<link rel="canonical">` для корня пишет его
 * без слэша. Разойдись они, карта сайта и canonical
 * указывали бы на два формально разных адреса одной страницы, то есть ровно
 * на ту неоднозначность, ради устранения которой canonical и ставится.
 */
export function absoluteUrl(path: string): string {
  const href = new URL(path, SITE_URL).href;
  return href.endsWith("/") ? href.slice(0, -1) : href;
}
