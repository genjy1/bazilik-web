/**
 * Даты последней содержательной правки каждой страницы.
 *
 * Один источник для двух потребителей: `lastmod` в sitemap.xml
 * (app/sitemap.ts) и заголовка `Last-Modified` на HTML-ответах
 * (next.config.ts). Разойдись они, робот получил бы два разных ответа на
 * вопрос «когда страница менялась».
 *
 * Отдельный файл, а не поле в `SITEMAP_ROUTES` (lib/site.ts): заголовок
 * нужен и страницам, которых в карте сайта нет (`/specialists`, `/cookies`
 * под noindex), а next.config.ts тянуть за собой весь lib/site.ts незачем.
 *
 * Правило: дата двигается рукой и только тогда, когда изменился текст или
 * структура страницы. Не при правке стилей, зависимостей или конфига —
 * иначе поле снова станет «датой деплоя», а поисковик перестаёт ему верить,
 * если оно меняется без реальных изменений. Дата сборки (`new Date()`)
 * здесь запрещена именно по этой причине.
 *
 * Формат — ISO-дата без времени: полночь UTC. Точнее сказать всё равно
 * нечего, а время в прошлом безопаснее времени в будущем — заголовок с
 * будущей датой робот считает недостоверным.
 */
export const PAGE_LAST_MODIFIED: Readonly<Record<string, string>> = {
  /** Секции главной и FAQ: слияние ветки code-review-round-2. */
  "/": "2026-09-05",
  /** Правки мета и текста раздела для специалистов (PR #15). */
  "/specialists": "2026-09-04",
  /** Заглушка cookie; при появлении текста политики — обновить. */
  "/cookies": "2026-09-05",
};

/**
 * Значение для заголовка `Last-Modified`: формат RFC 7231
 * («Fri, 05 Sep 2026 00:00:00 GMT»), который и ждёт HTTP.
 */
export function lastModifiedHeader(path: string): string {
  const iso = PAGE_LAST_MODIFIED[path];
  if (!iso) {
    throw new Error(`Нет даты правки для маршрута ${path} в lib/lastModified.ts`);
  }
  return new Date(`${iso}T00:00:00Z`).toUTCString();
}
