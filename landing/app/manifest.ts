import type { MetadataRoute } from "next";

/**
 * Веб-манифест. Next отдаёт его на `/manifest.webmanifest` и сам проставляет
 * `<link rel="manifest">` — руками в layout ничего добавлять не нужно.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * Почему `display: "browser"`, а не "standalone".
 *
 * "standalone" делает страницу устанавливаемой: браузер предлагает «Установить
 * приложение», и пользователь получает на домашнем экране иконку «Базилик»,
 * которая открывает лендинг без адресной строки — то есть выглядит как само
 * приложение. Но приложения ещё нет: ни в сторах, ни по ссылке (см. причины
 * в lib/schema.ts — там по той же логике нет `downloadUrl` и `installUrl`).
 * Установленный лендинг молча пообещал бы продукт и отдал промостраницу.
 *
 * "browser" оставляет манифесту всё, ради чего он здесь и нужен: имя и иконку
 * для «Добавить на главный экран» и закладок, цвет системной панели в Android
 * Chrome, язык и категорию. Установку как приложение он не предлагает.
 *
 * Менять на "standalone" — когда лендинг станет входом в само приложение,
 * а не рассказом о нём.
 * ─────────────────────────────────────────────────────────────────────────
 */
export default function manifest(): MetadataRoute.Manifest {
  return {
    /**
     * Стабильный идентификатор приложения. Без него браузер выводит id из
     * `start_url`, и любая будущая правка стартового адреса считалась бы
     * не обновлением, а новым приложением — с новой иконкой рядом со старой.
     */
    id: "/",

    /**
     * `name` показывается в диалоге установки и на сплеш-экране, `short_name` —
     * подписью под иконкой, где помещается ~12 знаков. Отсюда голое «Базилик»:
     * длинное имя система обрежет сама, и обрежет не там, где нужно.
     *
     * Строки не переиспользуются из layout.tsx осознанно: там TITLE и
     * DESCRIPTION подогнаны под выдачу (~60 и ~160 знаков), здесь ограничения
     * другие. Общий у них только смысл, а не длина.
     */
    name: "Базилик — меню на неделю",
    short_name: "Базилик",
    description:
      "Меню на неделю, список покупок и готовка по шагам. План пересобирается под остатки — без ручного учёта запасов.",

    start_url: "/",
    scope: "/",
    display: "browser",

    lang: "ru-RU",
    dir: "ltr",
    categories: ["food", "lifestyle"],

    /**
     * Цвет системной панели и подложки — те же токены, что у сайта:
     * `--accent` и `--ground` из globals.css. `theme_color` обязан совпадать
     * с `viewport.themeColor` в layout.tsx: разойдись они, панель браузера
     * перекрасилась бы при установке.
     *
     * Оба цвета взяты из светлой темы: манифест одного значения на тему не
     * знает, а светлая — тема по умолчанию.
     */
    theme_color: "#1f7a4d",
    background_color: "#f7f6f1",

    /**
     * Растр, а не logo.svg: SVG в манифесте читают не все браузеры, и это тот
     * случай, где запасной вариант нужен не «на всякий случай» — без иконки
     * система подставит скриншот страницы.
     *
     * PNG собраны из public/logo.svg с фоном `--ground`: прозрачность здесь
     * вредна, тёмный стебель на тёмном лаунчере пропадает.
     *
     * `maskable` — отдельным файлом и с меньшим логотипом: Android обрезает
     * иконку под форму лаунчера (круг, сквиркл), гарантирован только круг в
     * 80% ширины. Логотип в нём занимает 56% — вписанный в этот круг квадрат.
     * Тот же файл с `purpose: "any"` показывать нельзя: вне маски он выглядел
     * бы логотипом, потерявшимся в пустом поле.
     */
    icons: [
      { src: "/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
      { src: "/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
      { src: "/icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
    ],
  };
}
